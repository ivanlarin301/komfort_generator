"""Read-only helpers for Codex's local files (verified on Codex desktop 2026-10-01).

- Sessions:   ~/.codex/sessions/YYYY/MM/DD/rollout-<timestamp>-<thread-id>.jsonl
- Generated:  ~/.codex/generated_images/<thread-id>/*.png
These are internal formats of Codex; every caller must have a fallback (FR-1, design D4).
"""

from __future__ import annotations

import os
import re
import time
from pathlib import Path

_THREAD = re.compile(r"([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\.jsonl$", re.IGNORECASE)
IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg", ".webp"}


def codex_home() -> Path:
    return Path(os.environ.get("CODEX_HOME") or Path.home() / ".codex")


def latest_rollout() -> Path | None:
    sessions = codex_home() / "sessions"
    if not sessions.is_dir():
        return None
    files = list(sessions.rglob("rollout-*.jsonl"))
    return max(files, key=lambda p: p.stat().st_mtime) if files else None


def thread_id(rollout: Path) -> str | None:
    match = _THREAD.search(rollout.name)
    return match.group(1) if match else None


def generated_images(max_age_s: float | None = 3600) -> list[Path]:
    """Images generated by Codex, newest first: the current thread's folder, or any recent ones as a fallback."""
    root = codex_home() / "generated_images"
    if not root.is_dir():
        return []
    rollout = latest_rollout()
    thread = thread_id(rollout) if rollout else None
    folder = root / thread if thread and (root / thread).is_dir() else None
    candidates = [p for p in (folder or root).rglob("*") if p.suffix.lower() in IMAGE_SUFFIXES and p.is_file()]
    if folder is None and max_age_s is not None:
        now = time.time()
        candidates = [p for p in candidates if now - p.stat().st_mtime <= max_age_s]
    return sorted(candidates, key=lambda p: p.stat().st_mtime, reverse=True)
